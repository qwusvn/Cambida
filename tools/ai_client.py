"""Cambida AI Client — Cross-Model Helper

Allows Cambida (1.py, Telegram bot, background workers) to query external models
(Claude Sonnet 4.6, GPT-4o, Gemini 3.8 Flash) via the local Antigravity Tools proxy (port 8045).
"""

import json
import os
import sys
import urllib.request
import urllib.error

# Ensure UTF-8 stdout on Windows console
if sys.platform == "win32":
    try:
        sys.stdout.reconfigure(encoding="utf-8")
        sys.stderr.reconfigure(encoding="utf-8")
    except Exception:
        pass

DEFAULT_URL = os.environ.get("ANTIGRAVITY_TOOLS_URL", "http://127.0.0.1:8045/v1")
DEFAULT_KEY = os.environ.get("ANTIGRAVITY_TOOLS_KEY", "sk-3ce375830b884fb19f3700fc7769f495")
DEFAULT_MODEL = os.environ.get("ANTIGRAVITY_TOOLS_MODEL", "claude-sonnet-4-6")


def query_ai(
    prompt: str,
    model: str = DEFAULT_MODEL,
    system: str = None,
    temperature: float = 0.7,
    timeout: int = 120,
    api_url: str = DEFAULT_URL,
    api_key: str = DEFAULT_KEY,
) -> str:
    """Send a prompt to the proxy and return the complete string response.

    Args:
        prompt: The main user prompt or question.
        model: Target model name (e.g. 'claude-sonnet-4-6', 'gpt-4o', 'gemini-3.8-flash').
        system: Optional system instruction.
        temperature: Sampling temperature (0.0 to 2.0).
        timeout: Request timeout in seconds.
        api_url: Base URL of the proxy.
        api_key: API authorization key.

    Returns:
        The text response generated by the model.
    """
    messages = []
    if system:
        messages.append({"role": "system", "content": system})
    messages.append({"role": "user", "content": prompt})

    payload = {
        "model": model,
        "messages": messages,
        "temperature": temperature,
        "stream": False,
    }

    url = f"{api_url.rstrip('/')}/chat/completions"
    headers = {
        "Authorization": f"Bearer {api_key}",
        "Content-Type": "application/json",
    }

    data = json.dumps(payload).encode("utf-8")
    req = urllib.request.Request(url, data=data, headers=headers, method="POST")

    try:
        with urllib.request.urlopen(req, timeout=timeout) as response:
            result = json.loads(response.read().decode("utf-8"))
            choices = result.get("choices", [])
            if choices and "message" in choices[0]:
                return choices[0]["message"].get("content", "")
            return ""
    except urllib.error.HTTPError as exc:
        err_msg = exc.read().decode("utf-8", errors="replace")
        raise RuntimeError(f"Proxy HTTP Error {exc.code}: {err_msg}") from exc
    except Exception as exc:
        raise RuntimeError(f"Connection to Antigravity Tools Proxy failed ({url}): {exc}") from exc


def list_models(api_url: str = DEFAULT_URL, api_key: str = DEFAULT_KEY) -> list:
    """Return a list of all model IDs available from the proxy."""
    url = f"{api_url.rstrip('/')}/models"
    headers = {"Authorization": f"Bearer {api_key}"}
    req = urllib.request.Request(url, headers=headers, method="GET")

    try:
        with urllib.request.urlopen(req, timeout=10) as response:
            result = json.loads(response.read().decode("utf-8"))
            data = result.get("data", [])
            return [m.get("id") if isinstance(m, dict) else str(m) for m in data]
    except Exception as exc:
        raise RuntimeError(f"Failed to fetch models from proxy ({url}): {exc}") from exc


if __name__ == "__main__":
    q = " ".join(sys.argv[1:]) if len(sys.argv) > 1 else "Xin chào! Bạn là mô hình nào?"
    print(f"[*] Đang gửi câu hỏi tới {DEFAULT_MODEL} qua Antigravity Tools Proxy...")
    try:
        answer = query_ai(q)
        print("\n[Trả lời]:")
        print(answer)
    except Exception as e:
        print(f"[Lỗi]: {e}")
